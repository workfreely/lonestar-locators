/**
 * The DDL for the staging database the HTTP test runs against — printed, not applied.
 *
 * Generated from the policy sets rather than hand-written, so the table the store SELECTs from
 * has exactly the columns the store asks for. A hand-written list drifts the moment a field is
 * added, and the failure looks like a broken route rather than a stale fixture.
 *
 * The sixteen approval columns are deliberately ABSENT: the two migrations under test add them.
 *
 *   npx tsx scripts/tests/approvalCriteria.schema.ts > schema.sql
 */
import {
  ENRICHMENT_WRITABLE_FIELDS, IMAGE_FIELDS, OWNER_COMMISSION_FIELDS, OWNER_CREDIT_FIELDS,
  OWNER_CORRECTABLE_FIELDS,
} from "@/lib/propertyEnrichment/policy"
import { APPROVAL_COLUMNS } from "@/lib/propertyIntel/approvalCriteria"

/** Columns whose TYPE matters — to a CHECK, to the writer, or to the editor's round trip. */
const TYPED: Record<string, string> = {
  place_id: "text primary key",
  updated_at: "timestamptz",
  intel_enriched_at: "timestamptz",
  image_selection_state: "text",
  image_backup_state: "text",
  property_name: "text",
  address: "text",
  city: "text",
  state: "text",
  zip: "text",
  google_rating: "numeric(2,1)",
  nearby_landmark_1: "text",
  cross_streets: "text",
  gift_card_amount: "numeric(10,2)",
  gift_card_checked_at: "date",
  current_special_checked_at: "date",
  pricing_last_verified: "date",
  credit_minimum_status: "text",
  credit_minimum_score: "integer",
  credit_observed_approval_score: "integer",
  credit_screening_notes: "text",
  credit_screening_checked_at: "date",
}

/** Columns the ROUTE reads that no policy set contains. Listed, because a missing one turns the
 *  GET into a 500 and looks like a broken editor rather than a stale fixture. */
const ROUTE_ONLY = ["current_special_source", "gift_card_status"]

const cols = new Map<string, string>(Object.entries(TYPED))
for (const f of [...ENRICHMENT_WRITABLE_FIELDS, ...IMAGE_FIELDS, ...OWNER_COMMISSION_FIELDS,
                 ...OWNER_CREDIT_FIELDS, ...OWNER_CORRECTABLE_FIELDS, ...ROUTE_ONLY]) {
  if (!cols.has(f) && !APPROVAL_COLUMNS.includes(f)) cols.set(f, "text")
}

const out: string[] = []
out.push("-- GENERATED by scripts/tests/approvalCriteria.schema.ts — do not edit.")
out.push("drop view if exists public.property_field_provenance cascade;")
out.push("drop table if exists public.property_enrichment_events cascade;")
out.push("drop table if exists public.property_attributes cascade;")
out.push("drop table if exists public.property_attribute_keys cascade;")
out.push("drop table if exists public.property_catalog cascade;")
out.push(`create table public.property_catalog (\n  ${[...cols].map(([c, t]) => `${c} ${t}`).join(",\n  ")}\n);`)
// The live CHECKs on the credit columns, so staging is exactly as strict as production.
out.push(`alter table public.property_catalog
  add constraint property_catalog_credit_minimum_status_check
    check (credit_minimum_status is null or credit_minimum_status in ('reported_minimum','no_check_reported')),
  add constraint property_catalog_credit_minimum_score_check
    check (credit_minimum_score is null or credit_minimum_score between 300 and 850),
  add constraint property_catalog_credit_observed_approval_check
    check (credit_observed_approval_score is null or credit_observed_approval_score between 300 and 850);`)
out.push(`create table public.property_attribute_keys (
  attribute_key text primary key, category text, value_kind text default 'tristate'
);`)
out.push(`create table public.property_attributes (
  place_id text, attribute_key text, value text, value_text text,
  floorplan_specific boolean default false, applicability text,
  source_type text, source_reference text, verification_status text,
  checked_at timestamptz, merge_run_id uuid,
  primary key (place_id, attribute_key)
);`)
out.push(`create table public.property_enrichment_events (
  id bigserial primary key, seq bigserial, job_id text, place_id text, field_name text,
  action text check (action in ('written','skipped','rejected')),
  old_value text, new_value text, source_type text, source_reference text,
  verification_status text, reason text, checked_at timestamptz,
  created_at timestamptz not null default now()
);`)
out.push(`create view public.property_field_provenance as
  select distinct on (place_id, field_name)
    place_id, field_name, new_value as value, source_type, source_reference,
    verification_status, checked_at, created_at as written_at, job_id
  from public.property_enrichment_events
  where action = 'written'
  order by place_id, field_name, created_at desc, seq desc;`)
out.push(`insert into public.property_attribute_keys (attribute_key, category, value_kind) values
  ('private_yard','outdoor','tristate'),
  ('attached_garage','parking','tristate'),
  ('detached_garage','parking','tristate');`)
console.log(out.join("\n\n"))
