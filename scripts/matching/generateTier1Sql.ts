// Generate the Tier-1 enrichment SQL from the MEASURED proposal. READ-ONLY.
//
// The SQL is generated rather than hand-written so the place_ids, the expected
// current arrays used as guards, and the distances cannot drift from what was
// actually measured.
//
// Usage: npx tsx scripts/matching/generateTier1Sql.ts > supabase/manual/<file>.sql
import { readFileSync } from "node:fs"

type T1 = {
  placeId: string; propertyName: string; city: string; area: string
  addKeyword: string; distanceM: number; currentKeywords: string[]
  fieldWasEmpty: boolean; address: string | null
  existingProvenance: { source_type: string; verification_status: string; job_id: string } | null
}

const JOB_ID = "area_keyword_tier1_2026_10_01"
const rows: T1[] = JSON.parse(readFileSync("/tmp/tier1.json", "utf8"))

/** Postgres single-quoted literal. */
const q = (s: string) => `'${s.replace(/'/g, "''")}'`
/** Postgres text[] literal from a JS array, e.g. array['a','b'] or '{}'::text[]. */
const arr = (a: string[]) => (a.length === 0 ? `'{}'::text[]` : `array[${a.map(q).join(",")}]::text[]`)

const L: string[] = []
const p = (s = "") => L.push(s)

p(`-- ─────────────────────────────────────────────────────────────────────────────`)
p(`-- TIER 1 AREA-KEYWORD ENRICHMENT — ${rows.length} properties`)
p(`--`)
p(`-- Appends ONE canonical area label to property_catalog.location_keywords on the`)
p(`-- ${rows.length} properties that a CURRENT live lead's search can actually reach.`)
p(`--`)
p(`-- WHAT IS NOT TOUCHED: neighborhood, location, submarket, and every existing`)
p(`-- location_keywords value. No matching code changes; no commute change. The`)
p(`-- append lands each newly qualified property at rank 2, where exact and aliased`)
p(`-- keyword matches already sit, so no property moves between tiers.`)
p(`--`)
p(`-- THE EVIDENCE — three gates, all required, all from data already in the row:`)
p(`--   1. the property NAME contains the canonical area label, as a whole word;`)
p(`--   2. the property's OWN latitude/longitude is within 3 km (the Unleash search`)
p(`--      radius) of that area's catalogued centroid;`)
p(`--   3. the property does NOT already qualify for the area via the rank-4 address`)
p(`--      fallback — enriching one that does would promote it rank 4 -> rank 2 and`)
p(`--      reorder results. 3 such rows were excluded for this reason.`)
p(`-- Gate 2 is what rejects a marketing name: 38 name claims were refused, including`)
p(`-- a Dallas "Midtown Park" cluster claiming Midtown from 6.3-7.1 km away.`)
p(`-- 3 rows with a conflicting existing keyword are EXCLUDED, pending review.`)
p(`--`)
p(`-- PROVENANCE. Written to property_enrichment_events, the table built for exactly`)
p(`-- this (migration 20260925000000) and already holding 112,295 rows. Deliberately`)
p(`-- NOT to property_catalog.source or .verification_notes: \`source\` is row-level`)
p(`-- ("lb_master_verified+web_research" on the 5 rows that use it), not per-field, and`)
p(`-- \`verification_notes\` is an ENRICHMENT-WRITABLE property attribute`)
p(`-- (lib/propertyEnrichment/policy.ts), not a provenance sink — writing a note into`)
p(`-- either would overload a field whose meaning is already defined.`)
p(`--`)
p(`--   source_type         = 'google_places'  (the name and coordinates this inference`)
p(`--                         rests on both originate from Google Places)`)
p(`--   source_reference    = the place_id`)
p(`--   verification_status = 'inferred'  — NOT 'verified'. This is a derivation from`)
p(`--                         two facts in the row, not something read off the`)
p(`--                         property's own website.`)
p(`--`)
p(`-- ⚠ ONE PROVENANCE SIDE EFFECT, SURFACED RATHER THAN HIDDEN. The`)
p(`-- property_field_provenance view reports the LATEST written event per`)
p(`-- (place_id, field_name). ${rows.filter((r) => r.existingProvenance?.verification_status === "verified").length} of these ${rows.length} rows already have`)
p(`-- location_keywords provenance of official_property_site / verified, so after this`)
p(`-- runs that view will report those fields as google_places / inferred. That is`)
p(`-- arguably the honest reading — the field then holds a mix — and NOTHING is lost:`)
p(`-- property_enrichment_events is append-only, so the earlier verified event remains`)
p(`-- in full history. Flagged because it changes what the view says for those rows.`)
p(`--`)
p(`-- ROLLBACK-SAFE BY DESIGN:`)
p(`--   • one transaction — either all ${rows.length} land or none do;`)
p(`--   • every UPDATE is guarded on the row's EXACT expected current array, so a row`)
p(`--     edited since measurement (2026-10-01) is skipped silently rather than`)
p(`--     clobbered, and the verification queries below will show it as missed;`)
p(`--   • the provenance INSERT is driven by the UPDATE's RETURNING, so an event is`)
p(`--     recorded only for a row that actually changed — provenance can never claim`)
p(`--     a write that did not happen;`)
p(`--   • append-only: the new value is always the old array || one element, so no`)
p(`--     existing keyword can be dropped;`)
p(`--   • idempotent: re-running changes nothing, because the guard no longer matches`)
p(`--     once the keyword is present.`)
p(`--`)
p(`-- EXPECTED SIMULATION RESULTS to re-check after applying (simulated, not`)
p(`-- guaranteed — Places results shift over time):`)
p(`--   Ka'Leah (lead 84)        0 -> 3 qualified`)
p(`--   total qualified          53 -> 97`)
p(`--   total Beast Matches      46 -> 82`)
p(`--   leads reaching 6-8       1 -> 10`)
p(`--   leads at zero            1 -> 0`)
p(`-- Re-run: npx tsx scripts/matching/auditQualifiedPools.ts`)
p(`-- ─────────────────────────────────────────────────────────────────────────────`)
p()
p(`-- ═══ THE ${rows.length} ROWS ═══`)
p(`--`)
p(`-- ${"market".padEnd(12)} ${"area".padEnd(16)} ${"property".padEnd(42)} ${"dist".padStart(6)}  current location_keywords`)
for (const r of rows) {
  p(`-- ${r.city.padEnd(12)} ${r.area.padEnd(16)} ${r.propertyName.slice(0, 42).padEnd(42)} ${`${r.distanceM}m`.padStart(6)}  ${r.fieldWasEmpty ? "(EMPTY — fill)" : JSON.stringify(r.currentKeywords)}`)
  p(`--   place_id ${r.placeId}  ·  append ${JSON.stringify(r.addKeyword)}  ·  ${r.fieldWasEmpty ? "FILLING EMPTY FIELD" : `APPENDING to ${r.currentKeywords.length}`}${r.existingProvenance ? `  ·  existing provenance: ${r.existingProvenance.source_type}/${r.existingProvenance.verification_status}` : `  ·  no prior provenance`}`)
}
p()
p(`-- ═══ PRE-FLIGHT (read-only — run this FIRST and confirm ${rows.length} rows come back) ═══`)
p(`--`)
p(`-- select c.place_id, c.property_name, c.city, c.location_keywords`)
p(`--   from public.property_catalog c`)
p(`--  where c.place_id in (`)
p(`--        ${rows.map((r) => `'${r.placeId}'`).join(",\n--        ")}`)
p(`--        )`)
p(`--  order by c.city, c.property_name;`)
p()
p(`begin;`)
p()
p(`-- The proposal as data: place_id, the keyword to append, and the EXACT array the`)
p(`-- row is expected to hold right now (the guard).`)
p(`with proposed(place_id, add_kw, expected, dist_m) as (`)
p(`  values`)
rows.forEach((r, i) => {
  p(`    (${q(r.placeId)}, ${q(r.addKeyword)}, ${arr(r.currentKeywords)}, ${r.distanceM})${i === rows.length - 1 ? "" : ","}`)
})
p(`),`)
p(`-- Guarded append. A row whose keywords have changed since measurement fails the`)
p(`-- \`is not distinct from\` test and is left exactly as it is.`)
p(`upd as (`)
p(`  update public.property_catalog c`)
p(`     set location_keywords = c.location_keywords || array[p.add_kw]`)
p(`    from proposed p`)
p(`   where c.place_id = p.place_id`)
p(`     and c.location_keywords is not distinct from p.expected`)
p(`     and not (c.location_keywords @> array[p.add_kw])`)
p(`  returning c.place_id, p.add_kw, p.expected as old_kw,`)
p(`            c.location_keywords as new_kw, p.dist_m`)
p(`)`)
p(`-- One provenance event per row that ACTUALLY changed.`)
p(`insert into public.property_enrichment_events`)
p(`  (job_id, place_id, field_name, action, old_value, new_value,`)
p(`   source_type, source_reference, verification_status, reason, checked_at)`)
p(`select ${q(JOB_ID)},`)
p(`       u.place_id,`)
p(`       'location_keywords',`)
p(`       'written',`)
p(`       to_jsonb(u.old_kw)::text,`)
p(`       to_jsonb(u.new_kw)::text,`)
p(`       'google_places',`)
p(`       u.place_id,`)
p(`       'inferred',`)
p(`       format(`)
p(`         'area keyword %L added: property name contains canonical area label + property coordinates fall within the canonical area''s 3 km centroid radius (measured %s m). Appended only; no existing keyword altered; neighborhood/location/submarket untouched.',`)
p(`         u.add_kw, u.dist_m`)
p(`       ),`)
p(`       now()`)
p(`  from upd u;`)
p()
p(`commit;`)
p()
p(`-- ═══ VERIFICATION (read-only; run after the transaction) ═══`)
p(`--`)
p(`-- 1. All ${rows.length} rows now carry their keyword, and NOTHING was lost.`)
p(`--    Expect ${rows.length} rows, every \`kept_all_old\` true and every \`added\` true.`)
p(`--`)
p(`-- with expected(place_id, add_kw, old_kw) as (`)
p(`--   values`)
rows.forEach((r, i) => {
  p(`--     (${q(r.placeId)}, ${q(r.addKeyword)}, ${arr(r.currentKeywords)})${i === rows.length - 1 ? "" : ","}`)
})
p(`-- )`)
p(`-- select c.property_name, c.city, e.add_kw,`)
p(`--        c.location_keywords @> array[e.add_kw]      as added,`)
p(`--        c.location_keywords @> e.old_kw             as kept_all_old,`)
p(`--        cardinality(c.location_keywords) - cardinality(e.old_kw) as grew_by`)
p(`--   from expected e join public.property_catalog c using (place_id)`)
p(`--  order by added, c.city, c.property_name;`)
p(`--`)
p(`-- 2. Exactly ${rows.length} provenance events, all 'written' and 'inferred':`)
p(`--`)
p(`-- select action, source_type, verification_status, count(*)`)
p(`--   from public.property_enrichment_events`)
p(`--  where job_id = ${q(JOB_ID)}`)
p(`--  group by 1,2,3;`)
p(`--`)
p(`-- 3. The fields this must NOT touch are unchanged`)
p(`--    (expect neighborhood 7, location 10, submarket 706 — the pre-existing counts):`)
p(`--`)
p(`-- select count(neighborhood) as neighborhood, count(location) as location,`)
p(`--        count(submarket)    as submarket`)
p(`--   from public.property_catalog;`)
p(`--`)
p(`-- 4. No row lost a keyword anywhere in the table`)
p(`--    (expect 2482 + ${rows.filter((r) => r.fieldWasEmpty).length} = ${2482 + rows.filter((r) => r.fieldWasEmpty).length} non-empty, since ${rows.filter((r) => r.fieldWasEmpty).length} empty fields were filled):`)
p(`--`)
p(`-- select count(*) filter (where cardinality(location_keywords) > 0) as non_empty,`)
p(`--        count(*) filter (where cardinality(location_keywords) = 0) as empty`)
p(`--   from public.property_catalog;`)
p(`--`)
p(`-- 5. If a row was SKIPPED by its guard it appears here (expect 0 rows):`)
p(`--`)
p(`-- with expected(place_id, add_kw) as (`)
p(`--   values`)
rows.forEach((r, i) => {
  p(`--     (${q(r.placeId)}, ${q(r.addKeyword)})${i === rows.length - 1 ? "" : ","}`)
})
p(`-- )`)
p(`-- select c.place_id, c.property_name, c.location_keywords`)
p(`--   from expected e join public.property_catalog c using (place_id)`)
p(`--  where not (c.location_keywords @> array[e.add_kw]);`)
p(`--`)
p(`-- ═══ UNDO (only if needed — removes the keyword and logs the reversal) ═══`)
p(`--`)
p(`-- begin;`)
p(`--   with expected(place_id, add_kw) as (`)
p(`--     values`)
rows.forEach((r, i) => {
  p(`--       (${q(r.placeId)}, ${q(r.addKeyword)})${i === rows.length - 1 ? "" : ","}`)
})
p(`--   ),`)
p(`--   rev as (`)
p(`--     update public.property_catalog c`)
p(`--        set location_keywords = array_remove(c.location_keywords, e.add_kw)`)
p(`--       from expected e`)
p(`--      where c.place_id = e.place_id`)
p(`--        and c.location_keywords @> array[e.add_kw]`)
p(`--     returning c.place_id, e.add_kw, c.location_keywords as new_kw`)
p(`--   )`)
p(`--   insert into public.property_enrichment_events`)
p(`--     (job_id, place_id, field_name, action, old_value, new_value,`)
p(`--      source_type, source_reference, verification_status, reason, checked_at)`)
p(`--   select ${q(JOB_ID + "_undo")}, r.place_id, 'location_keywords', 'written',`)
p(`--          null, to_jsonb(r.new_kw)::text, 'google_places', r.place_id, 'inferred',`)
p(`--          format('reverted area keyword %L', r.add_kw), now()`)
p(`--     from rev r;`)
p(`-- commit;`)
p(`--`)
p(`-- array_remove drops only the appended label, so a property that legitimately`)
p(`-- carried that keyword BEFORE this job would lose it. None of these ${rows.length} did —`)
p(`-- the proposal skipped any row already naming its area — so the reversal is exact.`)

