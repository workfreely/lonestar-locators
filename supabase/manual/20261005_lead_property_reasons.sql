-- ════════════════════════════════════════════════════════════════════════════
-- CANONICAL CLIENT-PROPERTY INTELLIGENCE — "Why I chose this for you" (and the
-- commute result behind it) move out of lead_recommendations and into a relationship
-- table keyed by the client-property pair, so they survive moves between Favorites
-- and Recommendations.
--
-- SUPERSEDES supabase/manual/20261004_commute_anchor.sql, which is NOT to be applied:
-- it put the commute cache on lead_recommendations, where a move to Favorites
-- hard-deletes the row. The reason text would have survived in the canonical table
-- while its cache vanished — leaving "10 min to Fort Sam" on screen with nothing
-- backing it, so neither "does a commute reason already exist?" nor "is this anchor
-- stale?" could be answered. Both rules would have failed silently.
--
-- PREPARED FOR MANUAL APPLICATION. The migration ledger is out of sync, so
-- `supabase db push` would re-run 51 already-applied migrations against live
-- Property Intelligence data. Apply by hand in the Supabase SQL Editor for project
-- onwrrajmklxtnabekzcy, as one transaction, then run the verification queries at
-- the bottom. Rollback is at the very end.
--
-- WHY. Reasons lived on lead_recommendations.reasons, and every move between the
-- two collections HARD-DELETES the source row (removeSourceRow in DashboardClient).
-- Moving a recommendation to Favorites therefore destroyed its reasons, Favorites
-- had no reasons column at all, and re-adding a property later started empty.
--
-- The identity already existed: canonical_property_key ('pid:<place_id>') is
-- populated on 100% of rows in BOTH tables (17/17 favorites, 33/33 recommendations)
-- and is unique per (lead_id, key) in each. 43 distinct client-property pairs span
-- the two collections, and 7 pairs currently sit in BOTH at once — so the two are
-- overlapping views of one relationship, not exclusive buckets. That is exactly the
-- thing this table keys on.
--
-- ONE LIVE COPY. Neither collection stores reason text after this; both read and
-- write this row. lead_recommendations.reasons is left in place but becomes
-- non-authoritative (see step 6) — dropping it is a separate decision once the app
-- half is live, so this migration stays reversible.
--
-- lead_id scoping means reasons can never leak between clients: the client is half
-- the primary identity.
-- ════════════════════════════════════════════════════════════════════════════

begin;

-- ── 1. The table ────────────────────────────────────────────────────────────
-- Mirrors the workspace/tenancy shape of lead_favorites and lead_recommendations
-- exactly (workspace_id + owner_user_id + the shared ownership trigger + the
-- is_active_workspace_member policy), so it inherits the existing access model
-- rather than inventing a second one.
create table if not exists public.lead_property_reasons (
  id                     bigint generated by default as identity primary key,
  lead_id                bigint not null references public.leads(id) on delete cascade,
  -- 'pid:<google place id>' — the same value both collections already store.
  canonical_property_key text   not null,
  -- The client-facing reason fragments. Same <=3 promise the client page makes.
  reasons                text[] not null default '{}',
  workspace_id           uuid references public.workspaces(id) on delete cascade,
  owner_user_id          uuid references auth.users(id)        on delete set null,
  -- ── Commute cache + provenance ──────────────────────────────────────────
  -- Here, not on lead_recommendations: a commute figure is a function of
  -- (client anchor x property coordinates), which is precisely this pair. Sharing
  -- the row with the reasons means the cached minutes and the client-facing text
  -- they produced live and die together, survive a move to Favorites, and keep
  -- staleness computable.
  --   commute_minutes          cached Routes result; never recomputed per render
  --   commute_anchor_place_id  WHICH anchor produced it → staleness detection
  --   commute_computed_at      provenance
  -- No distance column: the approved copy is minutes only ("10 min to Fort Sam").
  commute_minutes          integer,
  commute_anchor_place_id  text,
  commute_computed_at      timestamptz,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now()
);

-- ── 1b. The commute destination, on the CLIENT ──────────────────────────────
-- The destination belongs to the client; the RESULT belongs to the client-property
-- pair above. `label` is the client-facing wording and is deliberately editable —
-- Places returns "Fort Sam Houston", the locator shortens it to "Fort Sam", and the
-- card reads "10 min to Fort Sam". `place_id` is the canonical target Routes is
-- called with: never a lat/lng, because a large site has no single point and a
-- guessed coordinate changes the answer by whole minutes (measured: 12 min vs 10).
alter table public.leads
  add column if not exists commute_anchor_label    text,
  add column if not exists commute_anchor_place_id text;

comment on column public.leads.commute_anchor_label is
  'Client-facing label for the commute destination ("Fort Sam"). Locator-editable.';
comment on column public.leads.commute_anchor_place_id is
  'Google Place ID of the commute destination — the canonical target for Routes API.';

-- THE canonical identity. One live reasons row per client-property pair — this is
-- what makes "edit in Favorites, see it in Recommendations" true by construction
-- rather than by synchronisation.
create unique index if not exists lead_property_reasons_pair_uidx
  on public.lead_property_reasons (lead_id, canonical_property_key);

create index if not exists lead_property_reasons_workspace_idx
  on public.lead_property_reasons (workspace_id);

-- Same cap the client page and lead_recommendations already enforce.
alter table public.lead_property_reasons
  drop constraint if exists lead_property_reasons_max3;
alter table public.lead_property_reasons
  add constraint lead_property_reasons_max3
  check (array_length(reasons, 1) is null or array_length(reasons, 1) <= 3);

comment on column public.lead_property_reasons.commute_minutes is
  'Cached Routes API drive time to the lead''s commute anchor, whole minutes. Computed '
  'once (on recommend, or on first anchor save) — never per render.';
comment on column public.lead_property_reasons.commute_anchor_place_id is
  'The anchor these minutes were computed against. A mismatch with the lead''s current '
  'commute_anchor_place_id means the stored commute reason is STALE — surfaced for an '
  'explicit recalculate, never rewritten silently.';

comment on table public.lead_property_reasons is
  'Canonical live client-property intelligence: "Why I chose this for you" reasons '
  'plus the commute cache behind them, for one CLIENT-PROPERTY pair. '
  'Survives moves between lead_favorites and lead_recommendations, and outlives '
  'removal from either, so re-adding a property restores its reasons. Scoped by '
  'lead_id, so reasons never leak between clients.';

-- ── 2. Tenancy trigger ──────────────────────────────────────────────────────
-- The same shared trigger lead_recommendations uses, so service-role/server writes
-- that do not set the columns themselves still get scoped rows.
drop trigger if exists trg_ownership on public.lead_property_reasons;
create trigger trg_ownership before insert on public.lead_property_reasons
  for each row execute function public.set_workspace_ownership();

-- ── 3. Lossless migration of existing reasons ───────────────────────────────
-- Every recommendation row carrying at least one reason is copied VERBATIM. No
-- filtering, no de-duplication of wording, no dropping of the Look & Lease strings:
-- there is no provenance proving which strings were hand-edited, so discarding any
-- of them could silently delete a locator's own words. Pruning outdated
-- special-derived text is a separate, reviewable step on the working data.
--
-- workspace_id/owner_user_id are carried across explicitly rather than relying on
-- the trigger, because a SQL Editor session has no auth.uid() to derive them from.
insert into public.lead_property_reasons
  (lead_id, canonical_property_key, reasons, workspace_id, owner_user_id, created_at, updated_at)
select r.lead_id,
       r.canonical_property_key,
       r.reasons,
       r.workspace_id,
       r.owner_user_id,
       coalesce(r.created_at, now()),
       now()
  from public.lead_recommendations r
 where r.canonical_property_key is not null
   and r.reasons is not null
   and array_length(r.reasons, 1) >= 1
on conflict (lead_id, canonical_property_key) do nothing;

-- Refuse to continue if the migration produced an unscoped row — one that its own
-- locator could never read back under the policy installed below. Same guard the
-- lead_recommendations workspace-scope migration used.
do $$
declare n int;
begin
  select count(*) into n from public.lead_property_reasons where workspace_id is null;
  if n > 0 then
    raise exception 'lead_property_reasons: % row(s) have a null workspace_id - aborting before RLS', n;
  end if;
end $$;

-- ── 4. RLS ──────────────────────────────────────────────────────────────────
alter table public.lead_property_reasons enable row level security;

do $$
declare p record;
begin
  for p in select policyname from pg_policies
            where schemaname = 'public' and tablename = 'lead_property_reasons' loop
    execute format('drop policy %I on public.lead_property_reasons', p.policyname);
  end loop;
end $$;

create policy "workspace members access lead_property_reasons"
  on public.lead_property_reasons for all
  using (public.is_active_workspace_member(workspace_id))
  with check (public.is_active_workspace_member(workspace_id));

-- ── 5. Share mint reads the canonical reasons ───────────────────────────────
-- Replaces the 4-arg body from 20260910000001 (the Vault-token version — NOT the
-- retired 3-arg one). The ONLY change is the reasons source: a LEFT JOIN onto
-- lead_property_reasons on the client-property pair, so a property with no reasons
-- row still snapshots, with '[]' exactly as before.
--
-- Snapshots keep their own frozen copy in client_recommendation_share_items. That
-- is deliberate immutability, not duplication of the working copy: already-sent
-- links must never change.
create or replace function public.lb_create_client_share(
  p_lead_id      bigint,
  p_token_hash   text,
  p_token_prefix text,
  p_raw_token    text
) returns table (share_id uuid, list_number integer, item_count integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ws        uuid;
  v_share_id  uuid;
  v_list_no   integer;
  v_count     integer;
  v_secret_id uuid;
begin
  select l.workspace_id into v_ws from public.leads l where l.id = p_lead_id;
  if v_ws is null then
    raise exception 'lb_create_client_share: lead % has no workspace', p_lead_id;
  end if;
  if not public.is_active_workspace_member(v_ws) then
    raise exception 'lb_create_client_share: not a member of this lead''s workspace';
  end if;

  select coalesce(max(s.list_number), 0) + 1 into v_list_no
    from public.client_recommendation_shares s where s.lead_id = p_lead_id;

  insert into public.client_recommendation_shares (lead_id, token_hash, token_prefix, list_number)
  values (p_lead_id, p_token_hash, p_token_prefix, v_list_no)
  returning id into v_share_id;

  -- Encrypt-and-store the raw token in Vault; keep only the pointer on the row.
  v_secret_id := vault.create_secret(
    p_raw_token,
    'client-share:' || v_share_id::text,
    'Raw client recommendation share token (Copy Link)'
  );
  update public.client_recommendation_shares
     set token_secret_id = v_secret_id where id = v_share_id;

  insert into public.client_recommendation_share_items
    (share_id, source_recommendation_id, property_name, property_address,
     property_image_url, property_website_url, reasons, sort_order)
  select v_share_id, r.id, r.property_name, r.property_address,
         r.property_image_url, r.property_website_url,
         coalesce(to_jsonb(pr.reasons), '[]'::jsonb),
         (row_number() over (order by r.created_at asc))::int
    from public.lead_recommendations r
    left join public.lead_property_reasons pr
           on pr.lead_id = r.lead_id
          and pr.canonical_property_key = r.canonical_property_key
   where r.lead_id = p_lead_id;

  select count(*)::int into v_count
    from public.client_recommendation_share_items ci where ci.share_id = v_share_id;

  update public.client_recommendation_shares s
     set item_count = v_count where s.id = v_share_id;

  return query select v_share_id, v_list_no, v_count;
end $$;

grant execute on function public.lb_create_client_share(bigint, text, text, text) to authenticated;

-- ── 6. Reuse-or-mint fingerprints the canonical reasons ─────────────────────
-- Replaces 20260910000002. Only the fingerprint's reasons source changes, so an
-- edit made in EITHER collection still changes the fingerprint and still forces a
-- fresh snapshot on the next Send List. Previously-SENT snapshots are still never
-- considered for reuse and never altered.
drop function if exists public.lb_prepare_client_share(bigint, text, text, text);

create or replace function public.lb_prepare_client_share(
  p_lead_id      bigint,
  p_token_hash   text,
  p_token_prefix text,
  p_raw_token    text
) returns table (share_id uuid, list_number integer, item_count integer, reused boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ws       uuid;
  v_existing uuid;
  v_list_no  integer;
  v_count    integer;
  v_cur_fp   text;
  v_snap_fp  text;
begin
  select l.workspace_id into v_ws from public.leads l where l.id = p_lead_id;
  if v_ws is null then
    raise exception 'lb_prepare_client_share: lead % has no workspace', p_lead_id;
  end if;
  if not public.is_active_workspace_member(v_ws) then
    raise exception 'lb_prepare_client_share: not a member of this lead''s workspace';
  end if;

  select string_agg(
           coalesce(r.property_name,'')       || E'\x1f' ||
           coalesce(r.property_address,'')     || E'\x1f' ||
           coalesce(r.property_image_url,'')   || E'\x1f' ||
           coalesce(r.property_website_url,'') || E'\x1f' ||
           coalesce(to_jsonb(pr.reasons), '[]'::jsonb)::text,
           E'\x1e' order by r.created_at asc)
    into v_cur_fp
    from public.lead_recommendations r
    left join public.lead_property_reasons pr
           on pr.lead_id = r.lead_id
          and pr.canonical_property_key = r.canonical_property_key
   where r.lead_id = p_lead_id;

  select s.id, s.list_number
    into v_existing, v_list_no
    from public.client_recommendation_shares s
   where s.lead_id = p_lead_id
     and s.sent_at is null
     and s.disabled_at is null
     and s.revoked_at is null
   order by s.list_number desc
   limit 1;

  if v_existing is not null then
    select string_agg(
             coalesce(ci.property_name,'')       || E'\x1f' ||
             coalesce(ci.property_address,'')     || E'\x1f' ||
             coalesce(ci.property_image_url,'')   || E'\x1f' ||
             coalesce(ci.property_website_url,'') || E'\x1f' ||
             coalesce(ci.reasons, '[]'::jsonb)::text,
             E'\x1e' order by ci.sort_order asc)
      into v_snap_fp
      from public.client_recommendation_share_items ci
     where ci.share_id = v_existing;

    if v_cur_fp is not distinct from v_snap_fp then
      select s.item_count into v_count
        from public.client_recommendation_shares s where s.id = v_existing;
      return query select v_existing, v_list_no, coalesce(v_count, 0), true;
      return;
    end if;
  end if;

  return query
    select c.share_id, c.list_number, c.item_count, false
      from public.lb_create_client_share(p_lead_id, p_token_hash, p_token_prefix, p_raw_token) c;
end $$;

grant execute on function public.lb_prepare_client_share(bigint, text, text, text) to authenticated;

commit;

