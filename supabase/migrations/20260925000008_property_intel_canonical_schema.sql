-- Canonical Property Intelligence schema reconciliation (ADDITIVE, non-destructive).
--
-- Reconciles the FINAL ~380-field Property Intelligence inventory against the live
-- schema. Every meaningful researched field gets a canonical structured destination
-- (catalog scalar, feature attribute, approval policy, specials, management company,
-- floor plan) rather than living only in property_source_raw. Commission stays
-- firewalled and untouched; images untouched; no existing value overwritten; the
-- feature-key dictionary is reconciled to canonical names (property_attributes is
-- empty, so no data migration and NO synonyms). Generated from the inventory.

-- 1) property_source_raw — lossless preservation landing table (Category 9 + verbatim).
create table if not exists public.property_source_raw (
  id            bigint generated always as identity primary key,
  place_id      text,
  market        text,
  source_file   text not null,
  source_sheet  text,
  source_row    text,
  column_label  text not null,
  raw_value     text,
  category      smallint,           -- 1..9 from the mapping audit
  mapped_to     text,               -- destination field/attribute/table, or NULL for Cat 9
  imported_at   timestamptz not null default now()
);
create index if not exists property_source_raw_place_idx  on public.property_source_raw (place_id);
create index if not exists property_source_raw_cat_idx     on public.property_source_raw (category);
create index if not exists property_source_raw_col_idx     on public.property_source_raw (column_label);
alter table public.property_source_raw enable row level security;

