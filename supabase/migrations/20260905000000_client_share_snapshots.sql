-- ============================================================================
-- Client Recommendation Shares — snapshot-per-list redesign
-- ============================================================================
-- Supersedes the "one active link per lead, resolved from LIVE lead_recommendations"
-- model. Each list is now an IMMUTABLE SNAPSHOT: the recommendations are copied
-- into client_recommendation_share_items at mint time, so editing the working
-- lead_recommendations later NEVER changes a previously sent list. A lead may have
-- MANY lists. Agent-facing status is Active / Disabled (reversible via disabled_at);
-- revoked_at remains INTERNAL only, for a hard security kill (never a product action).

-- ── shares: drop one-active-per-lead; rename paused_at; add list/snapshot/view cols
drop index if exists public.client_rec_shares_one_active;

alter table public.client_recommendation_shares
  rename column paused_at to disabled_at;

alter table public.client_recommendation_shares
  add column if not exists list_number        integer,
  add column if not exists sent_at             timestamptz,
  add column if not exists first_viewed_at     timestamptz,
  add column if not exists view_session_count  integer not null default 0,
  add column if not exists item_count          integer not null default 0;

-- Per-lead history ordering + fast List History query (all display fields are on
-- the row, so History needs no per-list joins).
create index if not exists client_rec_shares_lead_list_idx
  on public.client_recommendation_shares (lead_id, list_number desc);

comment on column public.client_recommendation_shares.disabled_at is
  'Agent-facing Disabled (reversible). null = Active. revoked_at stays internal-only for a hard kill.';
comment on column public.client_recommendation_shares.list_number is
  'Per-lead sequence (1,2,3…) assigned at mint. Many lists per lead; earlier lists are never mutated.';

-- ── snapshot items: the immutable copy of the recommendations at mint time ───
create table if not exists public.client_recommendation_share_items (
  id                       bigint generated by default as identity primary key,
  share_id                 uuid   not null references public.client_recommendation_shares(id) on delete cascade,
  source_recommendation_id bigint,                      -- provenance only; the source row may later be deleted
  property_name            text,
  property_address         text,
  property_image_url       text,
  property_website_url     text,
  reasons                  jsonb   not null default '[]'::jsonb,
  place_id                 text,
  sort_order               integer not null default 0,
  created_at               timestamptz not null default now()
);
create index if not exists client_rec_share_items_share_idx
  on public.client_recommendation_share_items (share_id, sort_order);

-- ── view sessions: deduped viewing sessions (no refresh spam) ────────────────
create table if not exists public.client_recommendation_share_views (
  id                 bigint generated by default as identity primary key,
  share_id           uuid not null references public.client_recommendation_shares(id) on delete cascade,
  session_started_at timestamptz not null default now(),
  last_seen_at       timestamptz not null default now(),
  hit_count          integer not null default 1
);
create index if not exists client_rec_share_views_share_idx
  on public.client_recommendation_share_views (share_id, last_seen_at desc);

-- ── RLS: items + views are written only by SECURITY DEFINER functions; members
--    may READ their own (for the List History view stats). anon reads nothing here.
alter table public.client_recommendation_share_items enable row level security;
alter table public.client_recommendation_share_views enable row level security;

drop policy if exists "members read share items" on public.client_recommendation_share_items;
create policy "members read share items"
  on public.client_recommendation_share_items for select
  using (exists (select 1 from public.client_recommendation_shares s
                  where s.id = share_id and public.is_active_workspace_member(s.workspace_id)));

drop policy if exists "members read share views" on public.client_recommendation_share_views;
create policy "members read share views"
  on public.client_recommendation_share_views for select
  using (exists (select 1 from public.client_recommendation_shares s
                  where s.id = share_id and public.is_active_workspace_member(s.workspace_id)));

-- ── mint: create a share + SNAPSHOT the CURRENT lead_recommendations ─────────
-- SECURITY DEFINER (the shares table has no INSERT policy by design); the caller's
-- workspace membership is verified explicitly so it cannot mint across tenants.
-- The raw token is generated in Node and only its sha256 reaches here.
create or replace function public.lb_create_client_share(
  p_lead_id      bigint,
  p_token_hash   text,
  p_token_prefix text
) returns table (share_id uuid, list_number integer, item_count integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ws       uuid;
  v_share_id uuid;
  v_list_no  integer;
  v_count    integer;
begin
  select l.workspace_id into v_ws from public.leads l where l.id = p_lead_id;
  if v_ws is null then
    raise exception 'lb_create_client_share: lead % has no workspace', p_lead_id;
  end if;
  if not public.is_active_workspace_member(v_ws) then
    raise exception 'lb_create_client_share: not a member of this lead''s workspace';
  end if;

  select coalesce(max(s.list_number), 0) + 1 into v_list_no
    from public.client_recommendation_shares s where s.lead_id = p_lead_id;

  insert into public.client_recommendation_shares (lead_id, token_hash, token_prefix, list_number)
  values (p_lead_id, p_token_hash, p_token_prefix, v_list_no)
  returning id into v_share_id;   -- trg_share_workspace sets workspace_id from the lead

  insert into public.client_recommendation_share_items
    (share_id, source_recommendation_id, property_name, property_address,
     property_image_url, property_website_url, reasons, sort_order)
  select v_share_id, r.id, r.property_name, r.property_address,
         r.property_image_url, r.property_website_url,
         coalesce(to_jsonb(r.reasons), '[]'::jsonb),
         (row_number() over (order by r.created_at asc))::int
    from public.lead_recommendations r
   where r.lead_id = p_lead_id;

  select count(*)::int into v_count
    from public.client_recommendation_share_items where share_id = v_share_id;
  update public.client_recommendation_shares set item_count = v_count where id = v_share_id;

  return query select v_share_id, v_list_no, v_count;
end $$;

grant execute on function public.lb_create_client_share(bigint, text, text) to authenticated;

-- ── record a deduped view SESSION (called by the public page on load) ────────
-- A refresh within ~30 min extends the current session (no new event); a gap
-- opens a new session and bumps view_session_count. Never tracks a disabled list.
create or replace function public.lb_record_client_share_view(p_token_hash text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_share_id uuid;
  v_last_id  bigint;
  v_last     timestamptz;
begin
  select id into v_share_id
    from public.client_recommendation_shares
   where token_hash = p_token_hash and revoked_at is null and disabled_at is null
   limit 1;
  if v_share_id is null then return; end if;

  select id, last_seen_at into v_last_id, v_last
    from public.client_recommendation_share_views
   where share_id = v_share_id
   order by last_seen_at desc limit 1;

  if v_last is not null and v_last > now() - interval '30 minutes' then
    update public.client_recommendation_share_views
       set last_seen_at = now(), hit_count = hit_count + 1
     where id = v_last_id;
  else
    insert into public.client_recommendation_share_views (share_id) values (v_share_id);
    update public.client_recommendation_shares
       set view_session_count = view_session_count + 1
     where id = v_share_id;
  end if;

  update public.client_recommendation_shares
     set last_viewed_at  = now(),
         first_viewed_at = coalesce(first_viewed_at, now())
   where id = v_share_id;
end $$;

grant execute on function public.lb_record_client_share_view(text) to anon, authenticated;

-- ── resolver: render the TOKEN'S SNAPSHOT, not live lead_recommendations ─────
-- Same output columns/shape as before (the public page is unchanged) EXCEPT the
-- status token is now 'active' | 'disabled'. Properties come from share_items.
drop function if exists public.lb_resolve_client_recommendations(text);

create or replace function public.lb_resolve_client_recommendations(p_token_hash text)
returns table (
  status            text,
  agent_name        text,
  agent_photo_url   text,
  agent_title       text,
  agent_phone       text,
  agent_email       text,
  agent_brokerage   text,
  smart_form_config jsonb,
  client_first_name text,
  properties        jsonb
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_share  record;
  v_status text;
begin
  select s.id, s.lead_id, s.disabled_at, s.revoked_at
    into v_share
    from public.client_recommendation_shares s
   where s.token_hash = p_token_hash
     and s.revoked_at is null
   limit 1;

  if v_share.id is null then
    return;   -- unknown and revoked are deliberately indistinguishable
  end if;

  v_status := case when v_share.disabled_at is not null then 'disabled' else 'active' end;

  return query
  select
    v_status,
    coalesce(
      nullif(trim(concat_ws(' ',
        nullif(trim(p.preferred_first_name), ''),
        nullif(trim(p.preferred_last_name), '')
      )), ''),
      nullif(trim(p.preferred_name), ''),
      nullif(trim(concat_ws(' ', p.first_name, p.last_name)), ''),
      'Your Locator'
    )::text,
    p.profile_photo_url::text,
    'Licensed Apartment Locator'::text,
    nullif(trim(p.phone_number), '')::text,
    nullif(trim(p.email), '')::text,
    coalesce(nullif(trim(p.brokerage), ''), nullif(trim(p.business_name), ''))::text,
    w.smart_form_config,
    nullif(trim(l.first_name), '')::text,
    case
      when v_status <> 'active' then null::jsonb
      else coalesce((
        select jsonb_agg(jsonb_build_object(
                 'name',       i.property_name,
                 'address',    i.property_address,
                 'imageUrl',   i.property_image_url,
                 'websiteUrl', i.property_website_url,
                 'reasons',    coalesce(i.reasons, '[]'::jsonb)
               ) order by i.sort_order asc)
          from public.client_recommendation_share_items i
         where i.share_id = v_share.id
      ), '[]'::jsonb)
    end
  from public.leads l
  join public.workspaces w on w.id = l.workspace_id
  join public.profiles   p on p.id = w.created_by
  where l.id = v_share.lead_id
  limit 1;
end $$;

grant execute on function public.lb_resolve_client_recommendations(text) to anon, authenticated;
