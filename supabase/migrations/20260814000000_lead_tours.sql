-- ============================================================================
-- Ready to Tour → Schedule Tour: canonical scheduled-tour appointment records
-- ============================================================================
-- One row per scheduled tour for a lead. A client may eventually have several
-- property tours in one touring block (11:00 A · 12:30 B · 2:00 C); the Tour
-- Follow-Up time is derived from the LAST active scheduled tour + 2 hours:
--
--     due_at = MAX(scheduled_at WHERE status = 'scheduled') + interval '2 hours'
--
-- This is the canonical appointment source the future Tour Workspace will CRUD;
-- the Tour Follow-Up ACTION itself stays in lead_next_actions (action_key
-- 'tour_follow_up', already allowed + deduped one-open-per-lead). scheduled_at is
-- a UTC instant — the locator's local wall-clock is converted with the resolved
-- IANA timezone (date-fns-tz fromZonedTime) before persistence.
--
-- RLS / ownership / updated_at all reuse the established Locator Beast patterns:
--   • workspace-scoped policy via public.is_active_workspace_member(workspace_id)
--   • public.set_workspace_ownership() BEFORE INSERT (stamps workspace_id + owner)
--   • public.set_updated_at() BEFORE UPDATE (shared touch-updated_at function)

create table if not exists public.lead_tours (
  id            bigint generated by default as identity primary key,
  lead_id       bigint not null references public.leads(id) on delete cascade,
  workspace_id  uuid references public.workspaces(id) on delete cascade,
  owner_user_id uuid,
  scheduled_at  timestamptz not null,
  property_id   bigint references public.lead_favorites(id) on delete set null,
  status        text not null default 'scheduled'
                  check (status in ('scheduled', 'completed', 'canceled')),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- Hot path: "last scheduled tour for this lead" (follow-up calc) + the future
-- workspace's per-lead ordered list. Plus the standard workspace scan index.
create index if not exists lead_tours_lead_idx      on public.lead_tours (lead_id, scheduled_at);
create index if not exists lead_tours_workspace_idx on public.lead_tours (workspace_id);

-- Tenant isolation — identical policy shape to leads / lead_next_actions / …
alter table public.lead_tours enable row level security;

drop policy if exists "workspace members access lead_tours" on public.lead_tours;
create policy "workspace members access lead_tours"
  on public.lead_tours for all
  using      (public.is_active_workspace_member(workspace_id))
  with check (public.is_active_workspace_member(workspace_id));

-- Auto-stamp workspace_id + owner_user_id on insert (same trigger every CRM table
-- uses, so no application code has to set them).
drop trigger if exists set_lead_tours_ownership on public.lead_tours;
create trigger set_lead_tours_ownership
  before insert on public.lead_tours
  for each row execute function public.set_workspace_ownership();

-- Keep updated_at current on every row update (shared function).
drop trigger if exists lead_tours_updated_at on public.lead_tours;
create trigger lead_tours_updated_at
  before update on public.lead_tours
  for each row execute procedure public.set_updated_at();
