-- Recommendations — the canonical per-client collection of properties Locator
-- Beast RECOMMENDS for a client (conceptually distinct from lead_favorites, which
-- are the properties the locator intentionally saved). This is the same shape and
-- tenant/RLS pattern as lead_favorites so both surfaces (Workspace Recommended
-- Properties + Beast Companion Recommendations) can read one canonical per-client
-- source. Read-only from the Companion in this pass; writes come later via the
-- existing verb bridge. No pricing/commute/match/specials/ordering fields yet —
-- deliberately minimal; enrichment is a future additive change.

create table if not exists public.lead_recommendations (
  id bigint generated by default as identity primary key,
  lead_id bigint not null references public.leads(id) on delete cascade,
  property_name text not null,
  property_url text not null,
  property_address text,
  property_image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists lead_recommendations_lead_id_idx on public.lead_recommendations (lead_id);

alter table public.lead_recommendations enable row level security;

create policy "Authenticated users can manage lead_recommendations"
  on public.lead_recommendations
  for all
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');
